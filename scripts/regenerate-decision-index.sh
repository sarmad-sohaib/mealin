#!/bin/sh
# Rewrite docs/decisions/INDEX.md from docs/decisions/YYYY-MM-DD-slug.md.
# Newest date first. Files that share a date are alphabetical by filename.
set -eu

root=$(CDPATH= cd -- "$(dirname "$0")/.." && pwd)
decisions_dir="$root/docs/decisions"
index="$decisions_dir/INDEX.md"

if [ ! -d "$decisions_dir" ]; then
  echo "missing $decisions_dir" >&2
  exit 1
fi

tmp_paths=$(mktemp)
tmp_keys=$(mktemp)
tmp_list=$(mktemp)
tmp_index=$(mktemp)
trap 'rm -f "$tmp_paths" "$tmp_keys" "$tmp_list" "$tmp_index"' EXIT

find "$decisions_dir" \
  -maxdepth 1 \
  -type f \
  -name '[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]-*.md' \
  -print > "$tmp_paths"

while IFS= read -r path; do
  [ -n "$path" ] || continue
  base=$(basename "$path")
  date=$(printf '%s\n' "$base" | cut -c 1-10)
  printf '%s|%s\n' "$date" "$base"
done < "$tmp_paths" > "$tmp_keys"

LC_ALL=C sort -t '|' -k1,1r -k2,2 "$tmp_keys" > "$tmp_list"

{
  printf '%s\n' '# Decisions'
  printf '\n'
  printf '%s\n' 'Generated by `scripts/regenerate-decision-index.sh`. Do not edit this file by hand.'
  printf '%s\n' 'Newest date first. Files that share a date are listed alphabetically by filename.'
  printf '\n'
} > "$tmp_index"

while IFS='|' read -r date base; do
  [ -n "${base:-}" ] || continue
  file="$decisions_dir/$base"

  title=$(awk '
    /^# / {
      sub(/^# /, "")
      print
      exit
    }
  ' "$file")

  decision=$(awk '
    /^## Decision[[:space:]]*$/ { take = 1; next }
    /^## / { if (take) exit }
    take {
      line = $0
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", line)
      if (line == "") next
      if (text != "") text = text " "
      text = text line
    }
    END {
      if (text == "") exit 2
      printf "%s\n", text
    }
  ' "$file") || {
    echo "missing Decision section in $base" >&2
    exit 1
  }

  if [ -z "$title" ]; then
    echo "missing title in $base" >&2
    exit 1
  fi

  printf -- '- %s [%s](%s): %s\n\n' "$date" "$title" "$base" "$decision" >> "$tmp_index"
done < "$tmp_list"

mv "$tmp_index" "$index"
