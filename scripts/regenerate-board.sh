#!/bin/sh
# Rewrite docs/BOARD.md from the Status line of each docs/tasks/NNN-*.md file.
# README.md is not a task.
set -eu

root=$(CDPATH= cd -- "$(dirname "$0")/.." && pwd)
tasks_dir="$root/docs/tasks"
board="$root/docs/BOARD.md"

if [ ! -d "$tasks_dir" ]; then
  echo "missing $tasks_dir" >&2
  exit 1
fi

tmp_rows=$(mktemp)
tmp_board=$(mktemp)
trap 'rm -f "$tmp_rows" "$tmp_board"' EXIT

: > "$tmp_rows"

for path in "$tasks_dir"/[0-9][0-9][0-9]*.md; do
  [ -f "$path" ] || continue
  base=$(basename "$path")
  id=$(printf '%s\n' "$base" | sed 's/-.*//')
  title=$(awk '/^# / { sub(/^# /, ""); print; exit }' "$path")
  status=$(awk '/^Status: / { sub(/^Status: /, ""); print; exit }' "$path")
  depends=$(awk '/^Depends: / { sub(/^Depends: /, ""); print; exit }' "$path")
  if [ -z "$title" ] || [ -z "$status" ]; then
    echo "missing title or Status in $base" >&2
    exit 1
  fi
  case "$status" in
    Ready|In\ progress|Blocked|Done) ;;
    *)
      echo "bad Status '$status' in $base" >&2
      exit 1
      ;;
  esac
  printf '%s|%s|%s|%s|%s\n' "$status" "$id" "$base" "$title" "${depends:-none}" >> "$tmp_rows"
done

write_section() {
  section="$1"
  printf '\n## %s\n\n' "$section"
  count=$(awk -F '|' -v section="$section" '$1 == section { c++ } END { print c + 0 }' "$tmp_rows")
  if [ "$count" -eq 0 ]; then
    printf '%s\n' 'None.'
    return
  fi
  awk -F '|' -v section="$section" '
    $1 == section { printf "- [%s](%s) — Depends: %s\n", $4, $3, $5 }
  ' "$tmp_rows" | LC_ALL=C sort
}

{
  printf '%s\n' '# Board'
  printf '\n'
  printf '%s\n' 'Generated by `scripts/regenerate-board.sh`. Do not edit this file by hand.'
  printf '%s\n' 'Work logs `docs/work/001-repo-setup.md` and `docs/work/002-execution-plan.md` are not tasks. Repo setup is Done.'
  printf '%s\n' 'Pick work from `docs/tasks/README.md`.'
  write_section 'Ready'
  write_section 'In progress'
  write_section 'Blocked'
  write_section 'Done'
  printf '\n'
} > "$tmp_board"

mv "$tmp_board" "$board"
